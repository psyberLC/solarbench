"""Aggregate results/<task>/*.json into results/RESULTS.md (summary table).

Usage: .venv/bin/python scripts/make_results_table.py
"""

import json
from pathlib import Path

from solarbench.eval.schema import rankable

ROOT = Path(__file__).resolve().parents[1] / "results"
# task-specific continuous metrics, shown when present: (summary key, column, unit)
METRICS = (("peak_push_force_N", "peak push", " N"), ("installed_torque_Nm", "final bolt torque", " N·m"),
           ("peak_installed_torque_Nm", "peak bolt torque", " N·m"))


def fmt(cell: dict) -> str:
    return f"{cell['rate']:.0%} [{cell['ci95'][0]:.0%}, {cell['ci95'][1]:.0%}]"


def fmt_cont(cell: dict | None, unit: str = "") -> str:
    if not cell or cell.get("mean") != cell.get("mean"):
        return "–"
    return f"{cell['mean']:.1f}{unit} [{cell['lo']:.1f}, {cell['hi']:.1f}]"


lines = [
    "# SolarBench results",
    "",
    "Rates are shown as value [95% Wilson CI]. Continuous metrics are shown as mean [95% bootstrap CI].",
    "Episodes with a simulator error are excluded from the rates and listed in their own column.",
    "Generated by `scripts/make_results_table.py`; per-episode data and provenance are in the JSON files.",
    "",
    "The last column says whether a row is rankable: held-out seeds, a recorded commit and an unmodified",
    "copy of the code. Rows that are not rankable are kept as history and are being re-run.",
    "",
]
for task_dir in sorted(p for p in ROOT.iterdir() if p.is_dir()):
    files = sorted(task_dir.glob("*.json"))
    if not files:
        continue
    lines += [f"## {task_dir.name}", ""]
    results = [json.loads(f.read_text()) for f in files]
    stages = [k for k in results[0]["summary"] if k.startswith("stage_")]
    metrics = [m for m in METRICS if any(m[0] in r["summary"] for r in results)]
    rows = []
    for r in results:
        s = r["summary"]
        prov = r["provenance"]
        label = r["policy"] if not r["policy"].startswith("jit:") else f"jit ({r.get('tag') or 'learned'})"
        rows.append([
            label, r["split"], prov["physics"].replace("Cfg", ""), f"{s['valid_episodes']}/{s['episodes']}",
            *[fmt(s[k]) for k in stages], fmt(s["safe_success"]), fmt(s["damage"]),
            *[fmt_cont(s.get(key), unit) for key, _, unit in metrics], fmt_cont(s.get("time_to_success_s"), " s"),
            f"{s['sim_error_rate']:.1%}", "no" if rankable(r) else "yes",
        ])
    header = ["policy", "split", "backend", "episodes", *[k.replace("stage_", "") for k in stages],
              "safe success", "damage", *[col for _, col, _ in metrics], "time to success", "sim error", "rankable"]
    lines += ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    lines += ["| " + " | ".join(row) + " |" for row in rows]
    lines.append("")
(ROOT / "RESULTS.md").write_text("\n".join(lines))
print((ROOT / "RESULTS.md").read_text())
